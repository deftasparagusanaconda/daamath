from posit_python import posit

n = 32

for bits in [
        0b01111111_11111111_11111111_11111111, # +maxPos
        0b01111111_11111111_111111111_1111110, 
        0b01111111_11111111_111111111_1111101,
        
        0b01000000_00000000_00000000_00000010, 
        0b01000000_00000000_00000000_00000001,
        0b01000000_00000000_00000000_00000000, # +1.0
        0b00111111_11111111_11111111_11111111, 
        0b00111111_11111111_11111111_11111110, 
        0b00111111_11111111_11111111_11111101, 
        
        0b00000000_00000000_00000000_00000010, 
        0b00000000_00000000_00000000_00000001, # +minPos
        0b00000000_00000000_00000000_00000000, #  0.0
        0b11111111_11111111_11111111_11111111, # -minPos
        0b11111111_11111111_11111111_11111110, 
        0b11111111_11111111_11111111_11111101, 
        
        0b11000000_00000000_00000000_00000010, 
        0b11000000_00000000_00000000_00000001, 
        0b11000000_00000000_00000000_00000000, # -1.0
        0b10111111_11111111_11111111_11111111, 
        0b10111111_11111111_11111111_11111110, 
        0b10111111_11111111_11111111_11111101, 
        
        0b10000000_00000000_00000000_00000010, 
        0b10000000_00000000_00000000_00000001, # -maxPos
        0b10000000_00000000_00000000_00000000]:#  NaR

    p = posit[n](bits=bits)
    
    fancy_bits = (
        f'<span style="color: var(--dm-red)">{p.S.replace('0', '□').replace('1', '■')}</span>'
        f'<span style="color: var(--dm-yellow)">{p.R[::-1].replace('0', '□').replace('1', '■')}</span>'
        f'<span style="color: var(--dm-gray)">{(p.R[-1]*(len(p.R)<31)).replace('0', '■').replace('1', '□')}</span>'
        f'<span style="color: var(--dm-green)">{p.E[::-1].replace('0', '□').replace('1', '■')}</span>'
        f'<span style="color: var(--dm-blue)">{p.F[::-1].replace('0', '□').replace('1', '■')}</span>')
    
#   also print the value p with a formula that is different for s = 0 and s = 1
    
    print(fancy_bits, '=', float(p))

print('</pre>')
